const languages = [
  { code: 'en', name: 'English', native: 'English' },
  { code: 'hi', name: 'Hindi', native: 'हिंदी' },
  { code: 'ml', name: 'Malayalam', native: 'മലയാളം' },
]

export const useLanguage = () => {
  const context = useContext(LanguageContext)
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider')
  }
  return context
}

const interpolate = (template, params = {}) =>
  Object.entries(params).reduce(
    (accumulator, [key, value]) => accumulator.replaceAll(`{${key}}`, String(value)),
    template,
  )

export const LanguageProvider = ({ children }) => {
  const [currentLanguage, setCurrentLanguage] = useState(() => {
    if (typeof window === 'undefined') return 'en'
    const stored = window.localStorage.getItem(STORAGE_KEY)
    return stored && translations[stored] ? stored : 'en'
  })

  useEffect(() => {
    if (typeof window !== 'undefined') {
      window.localStorage.setItem(STORAGE_KEY, currentLanguage)
    }
    document.documentElement.lang = currentLanguage
  }, [currentLanguage])

  const t = (key, params) => {
    const phrase = translations[currentLanguage]?.[key] ?? translations.en[key] ?? key
    return typeof phrase === 'string' ? interpolate(phrase, params) : phrase
  }

  const value = useMemo(
    () => ({
      currentLanguage,
      changeLanguage: setCurrentLanguage,
      t,
      languages,
    }),
    [currentLanguage],
  )

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}
