export const localizedCondition = (language, condition) => {
  if (!condition || language === 'en') return condition || weatherCopy.en.unavailableTitle
  const normalized = condition.toLowerCase()
  const match = conditionKeys.find(([needle]) => normalized.includes(needle))
  return match ? conditionCopy[language]?.[match[1]] ?? condition : condition
}

const localeMap = { en: 'en-IN', hi: 'hi-IN', ml: 'ml-IN' }

export const localizedDay = (language, day) => {
  if (day.date) {
    const parsed = new Date(`${day.date}T12:00:00`)
    if (!Number.isNaN(parsed.getTime())) {
      return new Intl.DateTimeFormat(localeMap[language] ?? 'en-IN', {
        weekday: 'short',
        day: 'numeric',
        month: 'short',
      }).format(parsed)
    }
  }
  if (day.day === 'Today') return weatherText(language, 'today')
  if (day.day === 'Tomorrow') return weatherText(language, 'tomorrow')
  return day.day
}
